#!/usr/bin/env node
// 앱 버전(루트 version.json)과 실제 사용 중인 오픈소스 패키지 목록을 빌드
// 시점에 스캔해 backend/src/generated/appInfo.ts로 굽는다("설정 > 정보" 화면이
// 이걸 API로 내려받아 보여준다, backend/CLAUDE.md의 "앱 정보(About)" 절 참고).
// `npm run build`/`npm run dev` 둘 다 backend 빌드 전에 이 스크립트를 먼저
// 돌린다(package.json의 build:backend) — 패키징(package:mac/linux/win)도
// 항상 `npm run build`를 먼저 거치므로 각 플랫폼 산출물에 자동으로 반영된다.

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');

function readJson(relPath) {
  return JSON.parse(fs.readFileSync(path.join(ROOT, relPath), 'utf-8'));
}

const versionFile = readJson('version.json');
const rootPkg = readJson('package.json');
const backendPkg = readJson('backend/package.json');
const frontendPkg = readJson('frontend/package.json');
const electronPkg = readJson('electron/package.json');

const APP_NAME = rootPkg.build?.productName ?? 'MyStock';
const APP_VERSION = versionFile.version;
// 작성자/저작권도 버전처럼 한 곳(루트 package.json)에서만 관리한다 — `author`는
// npm 문자열 형식("이름 <이메일>"), `build.copyright`는 electron-builder가 mac
// 앱 정보/Windows 파일 속성에도 그대로 쓰는 값이라 About 화면과 항상 일치한다.
const APP_AUTHOR = typeof rootPkg.author === 'string' ? rootPkg.author : null;
const APP_COPYRIGHT = rootPkg.build?.copyright ?? null;

// package.json의 "version" 필드는 npm/electron-builder가 그대로 읽는 값이라
// (electron-builder는 로컬 위치를 몰라 version.json을 직접 못 읽음) 항상
// version.json과 같은 값으로 맞춰둔다 — mac/linux/win 세 산출물 전부 이 필드
// 하나로 버전이 결정되므로, 여기서 한 번만 동기화하면 세 플랫폼이 자동으로
// 같은 버전을 쓰게 된다. 값이 이미 같으면(대부분의 경우) 파일을 다시 쓰지
// 않아 불필요한 git diff가 안 생긴다.
if (rootPkg.version !== APP_VERSION) {
  rootPkg.version = APP_VERSION;
  fs.writeFileSync(path.join(ROOT, 'package.json'), JSON.stringify(rootPkg, null, 2) + '\n');
}

// 실제로 앱에 번들되는 런타임 의존성만 대상으로 한다 — 각 워크스페이스의
// "dependencies"(devDependencies 제외, 빌드 도구는 최종 앱에 안 들어감)를
// 모으고, 워크스페이스끼리 서로 참조하는 내부 패키지(@mystock/*)는 뺀다.
// Electron 자체는 devDependencies에 있지만 패키징된 앱의 실제 런타임이라
// 별도로 포함시킨다.
const depNames = new Set();
for (const pkg of [rootPkg, backendPkg, frontendPkg, electronPkg]) {
  for (const name of Object.keys(pkg.dependencies ?? {})) {
    if (!name.startsWith('@mystock/')) depNames.add(name);
  }
}
depNames.add('electron');

function resolvePackageInfo(name) {
  const pkgJsonPath = path.join(ROOT, 'node_modules', name, 'package.json');
  if (!fs.existsSync(pkgJsonPath)) return null;
  const pkg = JSON.parse(fs.readFileSync(pkgJsonPath, 'utf-8'));
  const license =
    typeof pkg.license === 'string' ? pkg.license : (pkg.licenses?.map((l) => l.type).join(', ') ?? 'UNKNOWN');
  const homepage = typeof pkg.homepage === 'string' ? pkg.homepage : null;
  return { name, version: pkg.version ?? 'UNKNOWN', license, homepage };
}

const packages = Array.from(depNames)
  .map(resolvePackageInfo)
  .filter((p) => p !== null)
  .sort((a, b) => a.name.localeCompare(b.name));

const outDir = path.join(ROOT, 'backend/src/generated');
fs.mkdirSync(outDir, { recursive: true });

const header = `// AUTO-GENERATED by scripts/generate-app-info.cjs — 직접 수정하지 말 것.
// 소스: 루트 version.json(버전) + 루트 package.json(작성자/저작권) + 각 워크스페이스 package.json(패키지 목록,
// node_modules에 실제 설치된 버전/라이선스 기준). \`npm run build\`/\`npm run dev\`
// 시 매번 새로 만들어진다.
`;

const body = `${header}
export interface OssPackageInfo {
  name: string;
  version: string;
  license: string;
  homepage: string | null;
}

export const APP_NAME = ${JSON.stringify(APP_NAME)};
export const APP_VERSION = ${JSON.stringify(APP_VERSION)};
export const APP_AUTHOR: string | null = ${JSON.stringify(APP_AUTHOR)};
export const APP_COPYRIGHT: string | null = ${JSON.stringify(APP_COPYRIGHT)};
export const OSS_PACKAGES: OssPackageInfo[] = ${JSON.stringify(packages, null, 2)};
`;

fs.writeFileSync(path.join(outDir, 'appInfo.ts'), body);
console.log(`[generate-app-info] ${APP_NAME} v${APP_VERSION}, ${packages.length}개 패키지 → backend/src/generated/appInfo.ts`);
